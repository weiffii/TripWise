def curated_story(city, poi_id):
    if city != 'moscow' or poi_id not in MOSCOW:
        return None
    qid, lead, facts, sources = MOSCOW[poi_id]
    return {
        'short_text': f'{lead}\n\n{facts[0][1]}',
        'full_text': '\n\n'.join([lead, *(text for _, text in facts)]),
        'facts': [{'title': title, 'text': text} for title, text in facts],
        'sources': [{'title': title, 'url': url, 'attribution': 'Авторский пересказ по материалам источника',
                     'license': None, 'license_url': None} for title, url in sources],
        'match': {'wikidata_id': qid, 'confidence': 'high', 'method': 'editorial_catalog_id'},
        'image': None,
    }
